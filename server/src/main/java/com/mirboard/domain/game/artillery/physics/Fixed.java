    /** 칸 → 그 칸 가운데의 Q16. */
    public static long center(int cell) {
        return ((long) cell << SHIFT) + (ONE / 2);
    }

    /** 정수 제곱근 내림 ({@code n >= 0}). */
    public static int isqrt(long n) {
        if (n < 0) {
            throw new IllegalArgumentException("negative: " + n);
        }
        long r = (long) Math.sqrt((double) n);   // 시작값만 — 아래에서 정수로 바로잡는다
        while (r * r > n) {
            r--;
        }
        while ((r + 1) * (r + 1) <= n) {
            r++;
        }
        return (int) r;
    }
